# Mossheart's wispling menu sprites: wisp-menu.js + menu-drive.js in a headless studio live page, the sheets as PNGs
# (and the raw open, half shut, shut and eyeless shots) in -Work, then packed as data URIs into
# games/Mossheart/src/art/wisplings-sprites.js (MG.WISPLINGS), which the one-file build inlines. Rerun after the
# wisplings change in models.js (wisp-menu.js copies their pieces and faces). Takes the GPU: run it under gpu hold.
#   .\menu.ps1 -Port 9704                -> render and pack
#   .\menu.ps1 -Pack                     -> pack the PNGs already in -Work (sheets.json beside them)
#   .\menu.ps1 -Js C:\tmp\w.js           -> write the packed file elsewhere (to compare with the committed one)
param([int]$Port = 9333, [double]$Look = 0, [string]$Work = (Join-Path $env:TEMP "wisplings-menu"), [string]$Js = "", [switch]$Pack)
$ErrorActionPreference = "Stop"
$repo = (Resolve-Path (Join-Path $PSScriptRoot "..\..\..\..")).Path
if (-not $Js) { $Js = Join-Path $repo "games\Mossheart\src\art\wisplings-sprites.js" }
New-Item -ItemType Directory -Force $Work | Out-Null
Add-Type -AssemblyName System.Web.Extensions; $ser = New-Object Web.Script.Serialization.JavaScriptSerializer; $ser.MaxJsonLength = [int]::MaxValue
$utf8 = New-Object Text.UTF8Encoding $false
if (-not $Pack) {
  $run = Join-Path $Work "run.js"; $res = Join-Path $Work "result.json"
  $code = [IO.File]::ReadAllText((Join-Path $PSScriptRoot "wisp-menu.js")) + "`nglobalThis.MENU_LOOK = $Look;`n" + [IO.File]::ReadAllText((Join-Path $PSScriptRoot "menu-drive.js"))
  [IO.File]::WriteAllText($run, $code, $utf8)
  $sw = [Diagnostics.Stopwatch]::StartNew()
  & (Join-Path $repo "tools\voxel-live.ps1") -Headless -Port $Port -Open -Dims 40, 40, 32 -Grid 64 -File $run -Out $res
  if ($LASTEXITCODE) { throw "voxel-live failed ($LASTEXITCODE)" }
  "live {0:N1} s" -f $sw.Elapsed.TotalSeconds
  $r = $ser.DeserializeObject([IO.File]::ReadAllText($res))
  $png = { param($name, $url) [IO.File]::WriteAllBytes((Join-Path $Work "$name.png"), [Convert]::FromBase64String($url.Substring($url.IndexOf(",") + 1))) }
  foreach ($k in $r["sheets"].Keys) { & $png $k $r["sheets"][$k] }
  foreach ($k in $r["raw"].Keys) { $i = 0; foreach ($u in $r["raw"][$k]) { & $png "raw-$k-$i" $u; $i++ } }
  [IO.File]::WriteAllText((Join-Path $Work "sheets.json"), $ser.Serialize($r["json"]), $utf8)
  "H0 $($r["H0"]), mats $($r["mats"]), missing: $($r["missing"] -join ', ')"
  if ($r["warn"].Count) { "warn:"; $r["warn"] }
}
# pack: the sheets as data URIs into the json, with the models.js they were drawn from (its git blob), so a later
# change to it can flag the sprites as stale
$j = $ser.DeserializeObject([IO.File]::ReadAllText((Join-Path $Work "sheets.json")))
$models = "games/Mossheart/src/art/models.js"
$blob = (& git -C $repo hash-object $models).Trim()
$j["source"] = @{ models = $models; blob = $blob; generator = "games/MossheartEngine/studio/wisplings/menu.ps1" }
$bytes = 0
foreach ($name in $j["variants"].Keys) {
  foreach ($size in @($j["variants"][$name].Keys)) {
    $b = [IO.File]::ReadAllBytes((Join-Path $Work "$name@$size.png")); $bytes += $b.Length
    $j["variants"][$name][$size]["sheet"] = "data:image/png;base64," + [Convert]::ToBase64String($b)
  }
}
$head = "/* Mossheart's wispling menu sprites (Art): eight wisplings x five rows (idle, blink, peek, duck, hop) at 48 and 96 px`n" +
  "   frames, as PNG data URIs inline so the one-file build and offline play keep them. MG.WISPLINGS.about says how to`n" +
  "   read them. Generated by games/MossheartEngine/studio/wisplings/menu.ps1, do not edit. */`n"
[IO.File]::WriteAllText($Js, $head + "(function () {`n  const G = (window.MG = window.MG || {});`n  G.WISPLINGS = " + $ser.Serialize($j) + ";`n})();`n", $utf8)
"wrote $Js ({0:N0} KB of PNG, {1:N0} KB in all; models.js blob {2})" -f ($bytes / 1KB), ((Get-Item $Js).Length / 1KB), $blob.Substring(0, 12)
